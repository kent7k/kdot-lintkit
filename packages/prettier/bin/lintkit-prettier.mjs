#!/usr/bin/env node
// Run Prettier with a merged ignore file anchored at the project root (CWD).

 
import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const req = createRequire(process.cwd() + '/package.json')

function resolveCLI(pkgName, binName) {
  try {
    const pkgJson = req.resolve(`${pkgName}/package.json`)
    const pkg = JSON.parse(fs.readFileSync(pkgJson, 'utf8'))
    const rel =
      typeof pkg.bin === 'string'
        ? pkg.bin
        : (pkg.bin?.[binName] ?? Object.values(pkg.bin ?? {})[0])
    if (rel) return path.resolve(path.dirname(pkgJson), rel)
  } catch {}
  const localBin = path.join(process.cwd(), 'node_modules', '.bin', pkgName)
  return fs.existsSync(localBin) ? localBin : pkgName
}

// -------------------------------------------------------------------
// Resolve ignore sources robustly
// -------------------------------------------------------------------
const here = path.dirname(fileURLToPath(new URL('.', import.meta.url)))
const CWD = process.cwd()
const DEBUG = process.env.LINTKIT_PRETTIER_DEBUG === '1'

// central ignore（このパッケージの "ignore"）
// - ワークスペース直下からの実行
// - node_modules 経由の実行
// - dist/bin 経由の実行
// の全てをカバーする候補を用意
const centralCandidates = []
try {
  // 依存解決で実体を特定（workspace symlink / node_modules どちらでもOK）
  const pkgPath = req.resolve('@lintkit/prettier/package.json')
  centralCandidates.push(path.join(path.dirname(pkgPath), 'ignore'))
} catch {}
centralCandidates.push(
  path.resolve(here, '..', 'ignore'),        // packages/lintkit-prettier/ignore (bin/)
  path.resolve(here, '..', '..', 'ignore'),  // packages/lintkit-prettier/ignore (dist/bin/)
  path.resolve(CWD, 'packages', 'lintkit-prettier', 'ignore'),
)
const centralPaths = centralCandidates.filter((p, i, a) => fs.existsSync(p) && a.indexOf(p) === i)

// 共通 ignore（リポジトリ共有）: packages/tooling-ignores/common.ignore
const commonCandidates = [
  path.resolve(CWD, 'packages', 'tooling-ignores', 'common.ignore'),
  path.resolve(CWD, 'tooling-ignores', 'common.ignore'),
  path.resolve(here, '..', '..', 'tooling-ignores', 'common.ignore'),
  path.resolve(here, '..', '..', '..', 'tooling-ignores', 'common.ignore'),
]
const commonPaths = commonCandidates.filter((p, i, a) => fs.existsSync(p) && a.indexOf(p) === i)

// ローカル .prettierignore（任意）
const localIgnorePath = path.join(CWD, '.prettierignore')
const localPaths = fs.existsSync(localIgnorePath) ? [localIgnorePath] : []

// -------------------------------------------------------------------
// Args parsing
// -------------------------------------------------------------------
const argv = process.argv.slice(2)
const dd = argv.indexOf('--')
const head = dd === -1 ? argv : argv.slice(0, dd)
const tail = dd === -1 ? [] : argv.slice(dd + 1)

const args = []

// allow "check" / "write" shorthand as first token
if (head.length && (head[0] === 'check' || head[0] === 'write')) {
  args.push(head[0] === 'write' ? '--write' : '--check')
  head.shift()
}

// default mode: --check
if (
  !args.some((a) => a === '--check' || a === '--write') &&
  !head.includes('--check') &&
  !head.includes('--write')
) {
  args.push('--check')
}

// -------------------------------------------------------------------
// Build a merged ignore file at CWD and pass it via --ignore-path
// -------------------------------------------------------------------
if (!head.includes('--ignore-path') && !tail.includes('--ignore-path')) {
  const sources = [...commonPaths, ...centralPaths, ...localPaths]
  const parts = []

  for (const p of sources) {
    try {
      parts.push(`# ----- ${p}\n${fs.readFileSync(p, 'utf8')}`)
    } catch {}
  }

  const merged = `# GENERATED by lintkit-prettier - DO NOT EDIT${os.EOL}${parts.join('\n')}`
  const tmp = path.join(CWD, '.lintkit.prettierignore.tmp')
  fs.writeFileSync(tmp, merged)
  args.push('--ignore-path', tmp)

  const cleanup = () => {
    try {
      if (!DEBUG) fs.unlinkSync(tmp)
    } catch {}
  }
  if (DEBUG) {
    console.error('[lintkit-prettier] merged ignore at:', tmp)
    console.error(
      '[lintkit-prettier] sources:\n' +
        sources.map((p) => `  - ${p}`).join('\n'),
    )
  }
  process.on('exit', cleanup)
  process.on('SIGINT', () => { cleanup(); process.exit(130) })
  process.on('SIGTERM', () => { cleanup(); process.exit(143) })
}

// -------------------------------------------------------------------
// Default globs if none provided (broad; exclusions live in ignore file)
// -------------------------------------------------------------------
if (!head.some((a) => !a.startsWith('-'))) {
  head.push('**/*.{js,jsx,ts,tsx,md,mdx,json,yml,yaml,css,scss,html}')
  // 緊急避難（環境変数で有効化）: ignore 解決が失敗したときだけ早期枝刈り
  if (process.env.LINTKIT_PRETTIER_NEGATIVE_FALLBACK === '1') {
    head.push('!**/.next/**', '!**/.contentlayer/**', '!**/dist/**', '!**/build/**')
  }
}

// -------------------------------------------------------------------
// Invoke Prettier
// -------------------------------------------------------------------
const cli = resolveCLI('prettier', 'prettier')
const r = spawnSync(cli, [...args, ...head, ...tail], { stdio: 'inherit' })
process.exit(r.status ?? 1)
